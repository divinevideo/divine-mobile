#!/usr/bin/env bash
# ABOUTME: Writes one integration_test entrypoint that runs several E2E suites.
# ABOUTME: One entrypoint costs one Linux app build and launch instead of one per suite.

set -euo pipefail

usage() {
  echo "usage: $0 <integration_test/<name>_test.dart> <integration_test/...>..." >&2
  exit 64
}

[ "$#" -ge 2 ] || usage
output="$1"
shift

# Imports are written relative to the bundle, so it must sit directly in
# integration_test/: `flutter test` only runs a file in integration-test mode
# (on a device) when it lives under that directory.
case "$output" in
  integration_test/*/*) usage ;;
  integration_test/*_test.dart) ;;
  *) usage ;;
esac

imports=""
groups=""
index=0
for suite in "$@"; do
  case "$suite" in
    integration_test/*_test.dart) ;;
    *)
      echo "not an integration_test suite: $suite" >&2
      exit 64
      ;;
  esac
  if [ ! -f "$suite" ]; then
    echo "suite does not exist: $suite" >&2
    exit 1
  fi
  imports+="import '${suite#integration_test/}' as suite_$index;"$'\n'
  # The group is named after the file, so a failure still names its suite.
  groups+="  group('$suite', suite_$index.main);"$'\n'
  index=$((index + 1))
done

cat > "$output" <<EOF
// GENERATED by scripts/ci/write_service_suite_bundle.sh. Do not edit or commit.
@Tags(['service'])
library;

import 'package:flutter_test/flutter_test.dart';
import 'package:integration_test/integration_test.dart';

${imports}
void main() {
  IntegrationTestWidgetsFlutterBinding.ensureInitialized();
${groups}}
EOF

echo "Bundled $index suites into $output"
