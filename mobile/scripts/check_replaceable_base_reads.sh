#!/usr/bin/env bash
# Replaceable-publish base-read ratchet (#11317): the set of files that publish
# a replaceable Nostr kind without reading that kind through
# NostrClient.readCurrentVersion is frozen in
# scripts/baseline/replaceable_publishers.txt and may only ever SHRINK.
# See lib/list_ratchet.sh for the NEW/STALE/GROWTH semantics.
#
# Kinds 0, 3, 10000-19999 and 30000-39999 are replaced whole on every publish.
# A republish built from a relay read that did not finish deletes whatever
# only the unanswered relay held. readCurrentVersion settles every relay and
# reports found / absent / failed, so a publisher that reads its base through
# it cannot build on a partial answer.
#
# Detector: scripts/lib/replaceable_publish_detector.dart, a Dart AST over
# mobile/lib and mobile/packages/*/lib. A publish site is createAndSignEvent,
# a call through a signer typedef shaped like it, Event(pubkey, kind, ...), or
# NostrClient.sendContactList / sendProfileAwaitOk; a kind forwarded from a
# parameter is followed to the calls in the same file that fix it. An entry is
# `relpath<TAB>kind`, where kind `?` means the detector could not resolve it.
# The embedded-app bridge is exempt in the detector itself, with its reason.
#
# Entries are a worklist, not exemptions: each carries a trailing reason
# (`fixed site`, `open: #NNNN` or `review: ...`). Clear one by reading the
# kind through readCurrentVersion in the publishing file, then lock the win:
#   UPDATE_BASELINE=1 bash mobile/scripts/check_replaceable_base_reads.sh
# Inspect the sites with:
#   cd mobile && dart run scripts/lib/replaceable_publish_detector.dart lib packages/*/lib --detail

set -euo pipefail
export LC_ALL=C

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
MOBILE_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
DART_BIN="${REPLACEABLE_BASE_READS_DART:-dart}"

RATCHET_LABEL="replaceable_base_reads"
BASELINE_FILE="${REPLACEABLE_BASE_READS_BASELINE_FILE:-$SCRIPT_DIR/baseline/replaceable_publishers.txt}"
BASELINE_REPO_PATH="${REPLACEABLE_BASE_READS_BASELINE_REPO_PATH:-mobile/scripts/baseline/replaceable_publishers.txt}"
BASE_REF="${REPLACEABLE_BASE_READS_BASE_REF:-origin/main}"
ALLOW_NO_BASE="${REPLACEABLE_BASE_READS_ALLOW_NO_BASE:-0}"
ALLOW_NO_BASE_VAR="REPLACEABLE_BASE_READS_ALLOW_NO_BASE"
NEW_HINT="This file publishes a replaceable kind without reading it through NostrClient.readCurrentVersion. Build the replacement only on CurrentVersionFound or CurrentVersionAbsent, and publish nothing on CurrentVersionFailed (#11317)."
STALE_HINT="A publisher now reads its kind through readCurrentVersion, or stopped publishing it."
FOOTER="Replaceable publishers without a settled base read are frozen and may only
decrease. Read the kind through NostrClient.readCurrentVersion in the file that
publishes it. Inspect sites with:
  cd mobile && dart run scripts/lib/replaceable_publish_detector.dart lib packages/*/lib --detail"

emit_current() {
  (
    cd "$MOBILE_DIR"
    "$DART_BIN" run scripts/lib/replaceable_publish_detector.dart \
      lib packages/*/lib --path-prefix "$MOBILE_DIR"
  ) | LC_ALL=C sort -u
}

print_baseline_header() {
  cat <<'EOF'
# Frozen baseline: files under mobile/lib and mobile/packages/*/lib that
# publish a replaceable kind (0, 3, 10000-19999, 30000-39999) without reading
# that kind through NostrClient.readCurrentVersion (format: relpath<TAB>kind;
# kind ? = unresolved). Generated by scripts/check_replaceable_base_reads.sh.
# The set may only SHRINK (growth fails CI vs origin/main). Issue: #11317.
#
# A worklist, not exemptions. Every entry carries a reason:
#   fixed site: already reads settled; migrate it to readCurrentVersion.
#   open: #NNNN: a known incomplete-base republish tracked by that issue.
#   review: not an incomplete-base republish, and why: a new address, a whole
#     write with nothing to carry over, a kind that is not replaceable, a
#     publish only when a settled read finds none, an event never published
#     as itself, or code with no caller.
# Files that never publish an event as itself are exempt in the detector.
EOF
}

# shellcheck source=lib/list_ratchet.sh
source "$SCRIPT_DIR/lib/list_ratchet.sh"
run_list_ratchet
