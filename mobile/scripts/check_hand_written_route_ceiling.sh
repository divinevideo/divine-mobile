#!/usr/bin/env bash
# Hand-written route ceiling ratchet (#3572, epic #9121): every Dart file under
# mobile/lib that constructs a route by hand — `GoRoute(`, `ShellRoute(`,
# `StatefulShellRoute(` or `StatefulShellRoute.indexedStack(` — is frozen at its
# current count in scripts/baseline/hand_written_routes.txt, a per-file CEILING
# that may only ever DECREASE. New routes are `@TypedGoRoute` classes generated
# by go_router_builder; the conventions are in .claude/rules/routing.md.
#
# Detector (occurrences, in code only — see lib/dart_code_only.awk):
#   (GoRoute|ShellRoute|StatefulShellRoute)(\.[A-Za-z]+)?[[:space:]]*\(
# The required `(` keeps the typed forms out: `TypedGoRoute<…>(` and
# `TypedShellRoute<…>(` open with a type argument, and `GoRouteData.$route(`
# continues the identifier. There is deliberately no leading word boundary, so
# a subclass constructed as `FadeGoRoute(` still counts. Generated `*.g.dart`
# files are excluded by suffix, so a module's typed routes never count.
#
# Per-key NUMERIC ceiling: a migrated file must commit its lower ceiling in the
# same change (#8323); growth / new file / raised ceiling / unlocked shrink /
# drop-to-zero (STALE) fails.
#
# Regenerate after MIGRATING routes to @TypedGoRoute (never to raise):
#   UPDATE_BASELINE=1 bash mobile/scripts/check_hand_written_route_ceiling.sh
# Run (from repo root or mobile/): bash mobile/scripts/check_hand_written_route_ceiling.sh

set -euo pipefail
export LC_ALL=C

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
MOBILE_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
TAB="$(printf '\t')"

RATCHET_LABEL="hand_written_route_ceiling"
SCAN_DIR="${HAND_WRITTEN_ROUTE_SCAN_DIR:-$MOBILE_DIR/lib}"
PATH_PREFIX="${HAND_WRITTEN_ROUTE_PATH_PREFIX:-$MOBILE_DIR}"
BASELINE_FILE="${HAND_WRITTEN_ROUTE_BASELINE_FILE:-$SCRIPT_DIR/baseline/hand_written_routes.txt}"
BASELINE_REPO_PATH="${HAND_WRITTEN_ROUTE_BASELINE_REPO_PATH:-mobile/scripts/baseline/hand_written_routes.txt}"
BASE_REF="${HAND_WRITTEN_ROUTE_BASELINE_BASE_REF:-origin/main}"
ALLOW_NO_BASE="${HAND_WRITTEN_ROUTE_CEILING_ALLOW_NO_BASE:-0}"
ALLOW_NO_BASE_VAR="HAND_WRITTEN_ROUTE_CEILING_ALLOW_NO_BASE"

REQUIRE_BASELINE_UPDATE_ON_DECREASE=1

DETECT_RE='(GoRoute|ShellRoute|StatefulShellRoute)(\.[A-Za-z]+)?[[:space:]]*\('

NEW_HINT="Don't add hand-written GoRoute / ShellRoute / StatefulShellRoute constructions — declare the route as a @TypedGoRoute GoRouteData class and run build_runner. Conventions: .claude/rules/routing.md (Type-Safe Routes); #3572. Only real code counts — comments and string literals are stripped."
STALE_HINT="A file dropped its hand-written routes (migrated to @TypedGoRoute or removed)."
FOOTER="Hand-written route counts under mobile/lib are frozen and may only decrease.
Declare new routes with @TypedGoRoute (go_router_builder) instead.
See .claude/rules/routing.md and #3572 / epic #9121."

# Print "relpath<TAB>count" for every non-generated Dart file under SCAN_DIR that
# constructs a route by hand (in code only), by path.
emit_current() {
  find "$SCAN_DIR" \
    -type f -name '*.dart' \
    -not -path '*/l10n/generated/*' \
    -not -path '*/.dart_tool/*' \
    -not -path '*/build/*' \
    ! -name '*.g.dart' ! -name '*.freezed.dart' ! -name '*.gr.dart' \
    ! -name '*.config.dart' ! -name '*.mocks.dart' \
    -print0 2>/dev/null \
  | while IFS= read -r -d '' f; do
      count="$(awk -f "$SCRIPT_DIR/lib/dart_code_only.awk" "$f" 2>/dev/null \
        | grep -oE "$DETECT_RE" \
        | grep -c . || true)"
      count="${count//[[:space:]]/}"
      if [[ "${count:-0}" -gt 0 ]]; then
        printf '%s\t%s\n' "${f#"$PATH_PREFIX"/}" "$count"
      fi
    done \
  | LC_ALL=C sort -t "$TAB" -k1,1
}

print_baseline_header() {
  cat <<EOF2
# Frozen baseline: Dart files under mobile/lib constructing a route by hand
# (GoRoute( / ShellRoute( / StatefulShellRoute( / StatefulShellRoute.indexedStack(),
# each with its current count as a CEILING (format: relpath<TAB>count).
# Generated by scripts/check_hand_written_route_ceiling.sh. A ceiling may only
# SHRINK and a shrink must be committed here; a new route, a new file, a raised
# ceiling, or an unlocked shrink fails CI vs ${BASE_REF}. Declare new routes
# with @TypedGoRoute. Comments and string literals are not counted. Issue:
# #3572. Regenerate after migrating:
#   UPDATE_BASELINE=1 bash scripts/check_hand_written_route_ceiling.sh
EOF2
}

# shellcheck source=lib/numeric_ratchet.sh
source "$SCRIPT_DIR/lib/numeric_ratchet.sh"
run_numeric_ratchet
